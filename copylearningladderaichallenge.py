import google.generativeai as genai
import json, re
from difflib import SequenceMatcher
import time

# -----------------------------
# Gemini API setup
# -----------------------------
genai.configure(api_key="XXXXXXXXXXXXXXXX")
model = genai.GenerativeModel("gemini-2.5-flash")

print("Welcome to the STEM Learning Ladder! Type 'exit' to quit.\n")

# -----------------------------
# Game settings
# -----------------------------
level, score = 1, 0
settings = {
    "grade": "7th Grade",
    "subject": "Algebra",
    "max_diff": 10,
    "use_ai_answers": True,
    "grading_mode": "ai"   # options: "ai" (semantic) or "fast" (local fuzzy)
}

# -----------------------------
# Helper: Extract and parse JSON safely
# -----------------------------
def get_question(level):
    prompt = (
        f"Generate a {settings['subject']} question for {settings['grade']} students "
        f"at difficulty {level} (1=easy, {settings['max_diff']}=hard). "
        f"Return the result strictly in JSON with keys 'question' and 'answer'."
    )

    response = model.generate_content(prompt)
    text = response.text.strip()

    # Try to find a JSON object in Gemini’s response
    match = re.search(r"\{.*\}", text, re.DOTALL)
    if match:
        try:
            data = json.loads(match.group())
            return data.get("question", "No question"), data.get("answer", "No answer")
        except Exception as e:
            print("JSON parse error:", e)

    print("No valid JSON detected in Gemini output — retrying...")
    return "Error: could not parse question.", "N/A"

# -----------------------------
# Fuzzy local grading (offline)
# -----------------------------
def is_similar(user_ans, correct_ans, threshold=0.8):
    clean = lambda s: ''.join(ch for ch in s.lower() if ch.isalnum() or ch in '+-=x')
    a, b = clean(user_ans), clean(str(correct_ans))
    return SequenceMatcher(None, a, b).ratio() >= threshold

# -----------------------------
# Semantic Gemini grading (AI mode)
# -----------------------------
def ai_grade(question, user_ans, correct_ans):
    prompt = (
        f"You are grading a student's math answer.\n\n"
        f"Question: {question}\n"
        f"Correct Answer: {correct_ans}\n"
        f"Student Answer: {user_ans}\n\n"
        f"Determine if the student's answer is correct or equivalent, "
        f"allowing for misspellings, paraphrasing, units, or descriptive text. "
        f"Respond ONLY with 'correct' or 'incorrect'."
    )
    try:
        result = model.generate_content(prompt).text.strip().lower()
        return "correct" in result
    except Exception:
        return False

# -----------------------------
# Main Loop
# -----------------------------
while True:
    print(f"Level {level}/{settings['max_diff']} | Score: {score}")
    q, a = get_question(level)

    # Retry once automatically if the question parsing failed
    if "Error" in q:
        time.sleep(1)
        q, a = get_question(level)

    print(f"Question: {q}\n")

    ans = input("Your answer: ")
    if ans.lower() == "exit":
        print(f"Final Score: {score}")
        break

    # Optional: show AI's reference answer for comparison
    if settings["use_ai_answers"]:
        try:
            ai_solution = model.generate_content(f"Solve this {settings['subject']} question: {q}. "
                                                 f"Provide only the final numeric or symbolic answer.").text.strip()
            print(f"AI's Answer: {ai_solution}\n")
        except Exception:
            print("Could not fetch AI answer.\n")

    # --- Grading ---
    if settings["grading_mode"] == "ai":
        correct = ai_grade(q, ans, a)
    else:
        correct = is_similar(ans, a)

    # --- Feedback ---
    if correct:
        print("Correct!\n")
        score += 1
        level = min(level + 1, settings["max_diff"])
    else:
        print(f"Incorrect. Correct answer: {a}\n")
        level = max(1, level - 1)